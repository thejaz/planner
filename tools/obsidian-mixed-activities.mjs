import { assertTestVault } from './paths.mjs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import { plannerUI } from './planner-ui.mjs';
import { chooseCapture } from './capture-choice.mjs';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9237');
const checks = [], errors = [], path = '2011-04-01.md', summary = 'Mixed activity verification.md';
try {
  const page = plannerUI(browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('app://obsidian.md/')));
  await page.waitForFunction(() => typeof app !== 'undefined' && app.vault);
  await assertTestVault(page);
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner']?.controller.indexed || [...document.querySelectorAll('button')].some(b => b.textContent === 'Trust author and enable plugins'));
  const trust = page.getByRole('button', { name: 'Trust author and enable plugins', exact: true });
  if (await trust.count()) await trust.click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner']?.controller.indexed);
  await page.evaluate(() => app.setting.close());
  page.on('pageerror', e => errors.push(e.message));
  await page.evaluate(async ({ path, summary }) => {
    const p = app.plugins.plugins['thejaz-planner'], c = p.controller;
    c.settings.autoUpdate = false; c.settings.summaryPath = summary;
    const store = async (name, text) => {
      if (name === summary) text = text.replace(/^([A-Z]+) =/gm, (row, code) => c.settings.projectEmojis[code] ? `${c.settings.projectEmojis[code]} ${row}` : row);
      const f = app.vault.getAbstractFileByPath(name);
      if (f) await app.vault.modify(f, text); else await app.vault.create(name, text);
    };
    await store(path, '## plan for 1 apr 11\n### evening\n- [x] 15:00 (265) : frm\n- [x] 15:15 (15) : chp\n- [x] 15:20 (5) : zot\n- [x] 19:40 (n/a) : buffer\n- [x] 00:10 (60-210/270) : frm & party (synthetic event)\nFRM = 325\nCHP = 15\nZOT = 5\nSUM = 345\nKeep this annotation.\n');
    await store(summary, '### Days\n2011-04-01 = 345 🔥\n### Projects\nFRM = 325\nCHP = 15\nZOT = 5\n### Results\nDays (2011-04-01 - 2011-04-01): 1d\n');
    await c.index(); const v = await p.open(); v.switchMode('day'); await v.navigate('2011-04-01');
  }, { path, summary });
  const raw = name => page.evaluate(name => app.plugins.plugins['thejaz-planner'].controller.port.read(name), name);
  const original = await raw(path), originalSummary = await raw(summary);
  const row = () => page.locator('.planner-row[data-index="4"]');
  await row().locator('.planner-label').click();
  const state = await page.evaluate(path => {
    const day = app.plugins.plugins['thejaz-planner'].controller.days.get(path);
    return { credit: day.entries[4].credits, unknown: day.entries[4].unknownCredit, conflicts: day.diagnostics.filter(d => d.blocks || d.code === 'total-conflict') };
  }, path);
  assert.deepEqual(state, { credit: { FRM: 60 }, unknown: false, conflicts: [] });
  assert((await page.locator('.planner-total-line').innerText()).includes('5h 45m'));
  assert.equal(await row().locator('.planner-unknown-project').count(), 0);
  assert((await row().locator('.planner-project-warning').innerText()).includes('Ordinary activities'));
  assert(await row().getByRole('button', { name: 'Add PARTY as project', exact: true }).isVisible());
  assert.equal(await raw(path), original); assert.equal(await raw(summary), originalSummary);
  await page.screenshot({ path: 'artifacts/mixed-activities.png' });
  checks.push('Synthetic mixed entry contributes FRM 60m, restores 345m total, has no blocking/conflicting credit diagnostics, renders party as ordinary and offers explicit project registration without rewriting notes');
  await page.evaluate(() => { app.plugins.plugins['thejaz-planner'].controller.settings.autoUpdate = true; });
  await row().locator('input[type=checkbox]').click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2011-04-01.md')?.recordedSum === 285);
  await page.evaluate(async () => { await app.plugins.plugins['thejaz-planner'].controller.mutation; });
  assert((await raw(summary)).includes('2011-04-01 = 285'));
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2011-04-01.md')?.recordedSum === 345);
  await page.evaluate(async () => { await app.plugins.plugins['thejaz-planner'].controller.mutation; });
  assert.equal(await raw(path), original); assert.equal(await raw(summary), originalSummary);
  checks.push('Checkbox recalculation counts only project minutes, updates daily/summary totals to 285m and exact Undo restores both notes');
  await row().locator('.planner-label').click(); await row().getByRole('button', { name: 'Edit', exact: true }).click();
  const editInput = page.getByRole('textbox', { name: 'Edit activity input', exact: true });
  await editInput.fill('00:10 60 - 210 / 0 frm & party (synthetic event)'); await editInput.press('Enter');
  await page.waitForFunction(() => !document.querySelector('.planner-activity-editor'));
  assert((await raw(path)).includes('00:10 (60 - 210 / 270) : frm & party (synthetic event)'));
  assert((await raw(path)).includes('SUM = 345')); assert.equal(await raw(summary), originalSummary);
  assert.equal(await row().locator('.planner-duration-divider').textContent(), '/');
  checks.push('Inline spaced allocation and /0 retain explicit credits, calculate midnight elapsed time, bold the spaced numeric slash and keep productivity totals correct');
  await row().getByRole('button', { name: 'Add below', exact: true }).click();
  await chooseCapture(page, 'Entry mode', 'log');
  const input = page.getByRole('textbox', { name: 'Quick entry', exact: true });
  await input.fill('00:20 5 / 10 frm & party');
  const beforeInvalid = await raw(path); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.planner-preview-area')?.textContent.includes('Line 1'));
  assert.equal(await raw(path), beforeInvalid);
  await input.fill('00:20 5 - 5 / 10 frm & party (synthetic event)'); await input.press('Enter');
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2011-04-01.md')?.entries.length === 6);
  await page.evaluate(async () => { await app.plugins.plugins['thejaz-planner'].controller.mutation; });
  assert((await raw(path)).includes('5 - 5 / 10')); assert((await raw(path)).includes('Keep this annotation.'));
  checks.push('Quick entry refuses an ambiguous missing amount without writing, accepts corrected spaced components/allocation with Enter and preserves unrelated prose');
  assert.deepEqual(errors, []);
  const version = await page.evaluate(() => app.plugins.plugins['thejaz-planner'].manifest.version);
  await writeFile('artifacts/mixed-activities.json', JSON.stringify({ version, checks, errors }, null, 2)); console.log(JSON.stringify({ version, checks, errors }, null, 2));
} finally { await browser.close(); }
