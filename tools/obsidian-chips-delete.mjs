import { assertTestVault } from './paths.mjs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import { plannerUI } from './planner-ui.mjs';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9237');
const checks = [], errors = [], path = '2013-01-01.md';
try {
  const page = plannerUI(browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('app://obsidian.md/')));
  await page.waitForFunction(() => typeof app !== 'undefined' && app.vault);
  await assertTestVault(page);
  const trust = page.getByRole('button', { name: 'Trust author and enable plugins', exact: true });
  if (await trust.count()) await trust.click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner']?.controller.indexed);
  await page.evaluate(() => app.setting.close());
  page.on('pageerror', e => errors.push(e.message));
  await page.evaluate(async path => {
    const p = app.plugins.plugins['thejaz-planner'], c = p.controller; c.settings.autoUpdate = false;
    const text = '## plan for 1 jan 13\n### morning\n- [x] 09:00 (n/a) : awake\n- [ ] 09:20 (20) : chp\n- [ ] 09:30 (0) : buffer\n- [ ] 09:40 (?) : chp\n- [ ] 10:40 (50-30/60) : chp & mdr\n### afternoon\n---\nCHP = 0\nMDR = 0\nSUM = 0\nKeep this annotation.\n';
    const file = app.vault.getAbstractFileByPath(path);
    if (file) await app.vault.modify(file, text); else await app.vault.create(path, text);
    await c.index(); const v = await p.open(); v.switchMode('day'); await v.navigate('2013-01-01');
  }, path);
  const row = i => page.locator(`.planner-row[data-index="${i}"]`);
  const raw = () => page.evaluate(path => app.plugins.plugins['thejaz-planner'].controller.port.read(path), path);
  const settled = () => page.evaluate(async () => { await app.plugins.plugins['thejaz-planner'].controller.mutation; });
  const original = await raw();
  const styles = await page.locator('.planner-duration').evaluateAll(elements => elements.map(el => {
    const css = getComputedStyle(el);
    return { text: el.textContent, radius: css.borderRadius, background: css.backgroundColor, color: css.color, before: getComputedStyle(el, '::before').content, after: getComputedStyle(el, '::after').content };
  }));
  assert.deepEqual(styles.map(s => s.text), ['n/a', '20', '0', '?', '50-30/60']);
  assert(styles.every(s => s.radius === '999px' && s.background !== 'rgba(0, 0, 0, 0)' && ['none', 'normal'].includes(s.before) && ['none', 'normal'].includes(s.after)));
  assert(styles.every(s => s.background === styles[0].background && s.color === styles[0].color));
  await row(1).locator('.planner-label').click();
  const action = row(1).getByRole('button', { name: 'Edit', exact: true });
  assert.equal(await action.innerText(), 'edit');
  const actionStyle = await action.evaluate(el => ({ radius: getComputedStyle(el).borderRadius, background: getComputedStyle(el).backgroundColor, color: getComputedStyle(el).color }));
  assert.equal(actionStyle.radius, '999px'); assert.equal(actionStyle.background, 'rgb(255, 255, 255)'); assert.equal(actionStyle.color, 'rgb(17, 17, 17)');
  assert.equal(await page.getByRole('button', { name: 'Open source', exact: true }).innerText(), 'open source');
  assert.equal(await page.getByRole('button', { name: 'Activity', exact: true }).innerText(), 'Activity');
  assert.equal(await raw(), original);
  checks.push('Duration values retain purple chips; rounded action buttons have white backgrounds and black text with lowercase labels; tabs keep normal case and rendering preserves Markdown');
  await page.screenshot({ path: 'artifacts/chips-light.png' });
  await page.evaluate(() => { document.body.removeClass('theme-light'); document.body.addClass('theme-dark'); });
  await page.screenshot({ path: 'artifacts/chips-dark.png' });
  await page.evaluate(() => { document.body.removeClass('theme-dark'); document.body.addClass('theme-light'); });
  await action.hover();
  await page.waitForFunction(() => getComputedStyle([...document.querySelectorAll('.planner-row.is-current .planner-row-actions button')].find(el => el.textContent === 'Edit')).backgroundColor === 'rgb(244, 240, 255)');
  await page.screenshot({ path: 'artifacts/buttons-hover.png' });
  await page.mouse.down();
  await page.waitForFunction(() => {
    const css = getComputedStyle([...document.querySelectorAll('.planner-row.is-current .planner-row-actions button')].find(el => el.textContent === 'Edit'));
    return css.backgroundColor === 'rgb(228, 220, 247)' && css.transform !== 'none';
  });
  await page.screenshot({ path: 'artifacts/buttons-pressed.png' });
  await page.mouse.up(); await page.locator('.planner-activity-editor').waitFor(); await page.keyboard.press('Escape');
  assert.equal(await raw(), original);
  checks.push('Hover transitions to a pale purple tint; pointer press changes color and depresses the button; release still opens editing and Escape preserves the source');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await action.hover(); await page.mouse.down();
  const reduced = await action.evaluate(el => ({ transform: getComputedStyle(el).transform, duration: getComputedStyle(el).transitionDuration }));
  assert.equal(reduced.transform, 'none'); assert.equal(reduced.duration, '0s');
  await page.mouse.up(); await page.locator('.planner-activity-editor').waitFor(); await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await row(1).focus(); await page.keyboard.press('F2');
  const editor = page.locator('.planner-activity-editor');
  const save = editor.getByRole('button', { name: 'Save changes', exact: true });
  await save.focus();
  assert(await save.evaluate(el => document.activeElement === el && getComputedStyle(el).outlineStyle !== 'none'));
  await page.keyboard.press('Escape'); await editor.waitFor({ state: 'detached' });
  checks.push('Reduced motion disables transitions and pressing movement; compact edit retains a visible keyboard focus');
  await row(1).press('Delete');
  await page.waitForFunction(() => document.activeElement?.textContent === 'Delete row');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2013-01-01.md')?.entries.length === 4); await settled();
  assert(!(await raw()).includes('09:20 (20) : chp')); assert((await raw()).includes('Keep this annotation.'));
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2013-01-01.md')?.entries.length === 5); await settled();
  assert.equal(await raw(), original);
  checks.push('Delete then Enter confirms the focused delete action directly; only the selected row is removed and Undo restores exact source bytes');
  await row(1).locator('.planner-label').click(); await row(3).locator('.planner-label').click({ modifiers: ['Shift'] });
  await row(3).press('Delete');
  await page.waitForFunction(() => document.activeElement?.textContent === 'Delete rows');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2013-01-01.md')?.entries.length === 2); await settled();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2013-01-01.md')?.entries.length === 5); await settled();
  assert.equal(await raw(), original);
  checks.push('Multi-row Delete then Enter uses the same default focus and one Undo restores all selected activities');
  await row(1).locator('.planner-label').click(); await row(1).press('Delete');
  await page.waitForFunction(() => document.activeElement?.textContent === 'Delete row');
  await page.keyboard.press('Escape'); assert.equal(await raw(), original);
  checks.push('Escape still cancels deletion even while the delete button is the default');
  assert.deepEqual(errors, []);
  const version = await page.evaluate(() => app.plugins.plugins['thejaz-planner'].manifest.version);
  const report = { version, checks, styles, errors };
  await writeFile('artifacts/chips-delete.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
