import { assertTestVault } from './paths.mjs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9237');
const checks = [], errors = [];
try {
  const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('app://obsidian.md/'));
  assert(page);
  await assertTestVault(page);
  page.on('pageerror', e => errors.push(e.message));
  await page.evaluate(async () => {
    const p = app.plugins.plugins['thejaz-planner'], c = p.controller; c.settings.autoUpdate = false;
    const text = '## plan for 1 jan 13\n### morning\n- [x] 09:00 (60) : chp\n- [ ] 10:00 (60) : mdr\n\n### afternoon\n\n---\nCHP = 60\nSUM = 60\n';
    const f = app.vault.getAbstractFileByPath('2013-01-01.md');
    if (f) await app.vault.modify(f, text); else await app.vault.create('2013-01-01.md', text);
    c.ingest('2013-01-01.md', text);
    const v = await p.open(); v.draft = ''; v.captureOpen = false; await v.navigate('2013-01-01');
  });
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.timers.size === 0);
  const add = page.locator('.planner-row.is-current .planner-add-below');
  const toggle = page.locator('.planner-capture-toggle');
  assert(await add.isVisible()); assert(!(await toggle.isVisible()));
  await page.mouse.move(350, 50);
  await page.screenshot({ path: 'artifacts/planner-single-add-action.png' });
  checks.push('Selected row exposes Add below without a redundant collapsed add invitation or blank gap');
  await add.click();
  const quick = page.getByRole('textbox', { name: 'Quick entry', exact: true });
  assert(await quick.evaluate(el => el === document.activeElement));
  await quick.fill('09:30 chp');
  await page.getByRole('button', { name: 'Collapse activity editor', exact: true }).click();
  assert(await toggle.isVisible()); assert.equal(await toggle.textContent(), 'Continue your activity...');
  await toggle.click(); assert.equal(await quick.inputValue(), '09:30 chp');
  checks.push('Add below opens directly, while a collapsed draft keeps its useful Continue your activity invitation');
  await quick.fill(''); await page.getByRole('button', { name: 'Collapse activity editor', exact: true }).click();
  assert(!(await toggle.isVisible())); assert(await add.evaluate(el => el === document.activeElement));
  checks.push('Closing an empty editor returns focus to Add below instead of a hidden invitation');
  await page.getByRole('button', { name: 'Add activity to afternoon', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse activity editor', exact: true }).click();
  assert(await toggle.isVisible()); assert.equal(await toggle.textContent(), 'Add an activity...');
  checks.push('Empty sections without a row toolbar retain their add invitation');
  await page.locator('.planner-row').nth(1).click();
  assert(!(await toggle.isVisible())); await add.click();
  await quick.fill('10:30 30 jib'); await quick.press('Enter');
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2013-01-01.md')?.entries.length === 3 && !app.workspace.getLeavesOfType('thejaz-planner')[0].view.captureOpen && getComputedStyle(document.querySelector('.planner-capture')).display === 'none');
  assert(!(await toggle.isVisible()));
  assert(await add.evaluate(el => el === document.activeElement));
  checks.push('Successful submission leaves one Add below control at the new row with keyboard focus');
  assert.deepEqual(errors, []);
  await writeFile('artifacts/planner-add-redundancy.json', JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); }
