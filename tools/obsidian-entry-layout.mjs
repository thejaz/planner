import { assertTestVault } from './paths.mjs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import { plannerUI } from './planner-ui.mjs';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9237');
const checks = [], errors = [], path = '2014-01-01.md';
try {
  const page = plannerUI(browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('app://obsidian.md/')));
  await page.waitForFunction(() => typeof app !== 'undefined' && app.vault);
  await assertTestVault(page);
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner']?.controller.indexed || [...document.querySelectorAll('button')].some(button => button.textContent === 'Trust author and enable plugins'));
  const trust = page.getByRole('button', { name: 'Trust author and enable plugins', exact: true });
  if (await trust.count()) await trust.click();
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner']?.controller.indexed);
  await page.evaluate(() => app.setting.close());
  page.on('pageerror', error => errors.push(error.message));
  await page.evaluate(async path => {
    const p = app.plugins.plugins['thejaz-planner'], c = p.controller; c.settings.autoUpdate = false;
    const text = '## plan for 1 jan 14\n### morning\n- [x] 09:00 (n/a) : awake\n- [ ] 09:20 (20) : chp\n- [ ] 09:40 (0) : buffer\n### afternoon\n- [ ] 14:00 (100-100/200) : chp & mdr\n- [ ] 14:30 (?) : meal\n---\nCHP = 0\nMDR = 0\nSUM = 0\nKeep this annotation.\n';
    const file = app.vault.getAbstractFileByPath(path);
    if (file) await app.vault.modify(file, text); else await app.vault.create(path, text);
    await c.index(); const v = await p.open(); v.entryMode = 'plan'; v.draft = ''; v.captureOpen = false; v.switchMode('day'); await v.navigate('2014-01-01');
  }, path);
  const row = i => page.locator(`.planner-row[data-index="${i}"]`);
  const raw = () => page.evaluate(path => app.plugins.plugins['thejaz-planner'].controller.port.read(path), path);
  const settled = () => page.evaluate(async () => { await app.plugins.plugins['thejaz-planner'].controller.mutation; });
  const waitRows = count => page.waitForFunction(count => app.plugins.plugins['thejaz-planner'].controller.days.get('2014-01-01.md')?.entries.length === count, count);
  const aligned = async () => {
    assert.equal(await page.locator('.planner-row').first().evaluate(el => getComputedStyle(el).columnGap), '8px');
    const columns = await page.locator('.planner-row').evaluateAll(rows => rows.map(row => ['.planner-time', '.planner-duration', '.planner-label'].map(selector => row.querySelector(selector).getBoundingClientRect().left)));
    for (let column = 0; column < 3; column++) assert(Math.max(...columns.map(row => row[column])) - Math.min(...columns.map(row => row[column])) < 1, JSON.stringify(columns));
  };
  const original = await raw();
  await row(1).locator('.planner-label').click(); await aligned();
  assert(await page.locator('.planner-duration-divider').evaluateAll(elements => elements.every(el => el.textContent === '/' && Number(getComputedStyle(el).fontWeight) >= 700)));
  assert.equal(await page.locator('.planner-duration').nth(3).textContent(), '100-100/200');
  assert.equal(await page.locator('.planner-duration').first().textContent(), 'n/a');
  assert.equal(await page.locator('.planner-duration').first().locator('strong').count(), 0);
  assert(Number(await page.locator('.planner-duration').first().evaluate(el => getComputedStyle(el).fontWeight)) < 700);
  assert.equal(await page.locator('.planner-duration').nth(3).locator('strong').textContent(), '/');
  assert.equal(await raw(), original);
  await page.screenshot({ path: 'artifacts/entry-columns.png' });
  await page.setViewportSize({ width: 740, height: 850 }); await aligned();
  // Row highlights extend 6px into the existing view padding; the view itself must not scroll horizontally.
  assert(await page.locator('.view-content.planner').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'artifacts/entry-columns-narrow.png' });
  await page.setViewportSize({ width: 1024, height: 850 });
  checks.push('Time, duration and activity columns align across sections with 8px gaps at normal/narrow widths; numeric duration slash is bold, n/a stays normal weight and Markdown bytes remain unchanged');
  const compose = async index => {
    await row(index).locator('.planner-label').click(); await row(index).getByRole('button', { name: 'Add below', exact: true }).click();
    return page.getByRole('textbox', { name: 'Quick entry', exact: true });
  };
  let input = await compose(1); await input.fill('09:25 5 chp'); await input.press('Enter'); await waitRows(6); await settled();
  assert((await raw()).includes('- [ ] 09:25 (5) : chp')); await aligned();
  checks.push('Plain Enter adds a single quick-entry activity and preserves shared column alignment');
  const beforeBatch = await raw();
  input = await compose(2); await input.fill('09:30 5 chp'); await input.press('Control+Enter');
  assert.equal(await input.inputValue(), '09:30 5 chp\n'); assert.equal(await raw(), beforeBatch);
  await input.pressSequentially('09:35 5 mdr');
  const caret = await input.evaluate(el => el.selectionStart);
  await page.evaluate(async () => { await app.workspace.getLeavesOfType('thejaz-planner')[0].view.refresh(); });
  assert.equal(await input.inputValue(), '09:30 5 chp\n09:35 5 mdr');
  assert.equal(await input.evaluate(el => el.selectionStart), caret); assert.equal(await input.evaluate(el => el.rows), 2);
  await input.press('Enter'); await waitRows(8); await settled();
  const batch = await raw();
  assert(batch.includes('- [ ] 09:30 (5) : chp\n- [ ] 09:35 (5) : mdr'));
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await waitRows(6); await settled(); assert.equal(await raw(), beforeBatch);
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await waitRows(8); await settled(); assert.equal(await raw(), batch);
  checks.push('Ctrl+Enter inserts a draft line without writing; draft/caret/height survive refresh; Enter saves all lines and one Undo/Redo restores the batch exactly');
  input = await compose(4); await input.fill('09:36 1 chp\n0 frm'); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.planner-preview-area')?.textContent.includes('Line 2'));
  assert.equal(await raw(), batch); assert.equal(await input.inputValue(), '09:36 1 chp\n0 frm');
  await input.fill('09:36 1 chp'); await input.press('Enter'); await waitRows(9); await settled();
  assert((await raw()).includes('09:36 (1) : chp'));
  checks.push('Invalid multiline Enter submission writes nothing and retains the complete draft; correcting it and pressing Enter succeeds');
  input = await compose(5); await input.fill('09:37 1 chp');
  const beforeCompose = await raw();
  await input.evaluate(el => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true, isComposing: true })));
  assert.equal(await raw(), beforeCompose);
  await input.evaluate(el => { for (let i = 0; i < 2; i++) el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true })); });
  await waitRows(10); await settled();
  assert.equal((await raw()).split('09:37 (1) : chp').length - 1, 1);
  assert((await raw()).includes('Keep this annotation.'));
  checks.push('IME composition does not submit; rapid Enter events cannot submit the same draft twice; unrelated prose survives');
  assert.deepEqual(errors, []);
  const version = await page.evaluate(() => app.plugins.plugins['thejaz-planner'].manifest.version);
  const report = { version, checks, errors };
  await writeFile('artifacts/entry-layout.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
