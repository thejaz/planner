import { assertTestVault } from './paths.mjs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9237');
const checks = [], errors = [];
try {
  const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().startsWith('app://obsidian.md/'));
  assert(page);
  await assertTestVault(page);
  page.on('pageerror', e => errors.push(e.message));
  if (await page.locator('.modal').count()) await page.keyboard.press('Escape');
  await page.evaluate(async () => {
    const p = app.plugins.plugins['thejaz-planner'], c = p.controller; c.settings.autoUpdate = false;
    const raw = '## plan for 1 jan 11\n### morning\n- [x] 11:00 (n/a) : awake\n- [x] 12:00 (60) : chp\n\n### afternoon\n\n---\nCHP = 60\nSUM = 60\n\nKeep me.\n';
    const file = app.vault.getAbstractFileByPath('2011-01-01.md');
    if (file) await app.vault.modify(file, raw); else await app.vault.create('2011-01-01.md', raw);
    c.ingest('2011-01-01.md', raw);
    const v = await p.open(); v.draft = ''; v.captureOpen = false; await v.navigate('2011-01-01');
  });
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.timers.size === 0);
  const initial = await page.evaluate(() => app.plugins.plugins['thejaz-planner'].controller.port.read('2011-01-01.md'));
  const toggle = page.locator('.planner-capture-toggle');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await page.getByRole('textbox', { name: 'Quick entry', exact: true }).count(), 0);
  assert(await page.locator('.planner-capture').evaluate(el => el.getBoundingClientRect().height <= 40));
  await page.locator('.planner-row.is-current').scrollIntoViewIfNeeded(); await page.mouse.move(1, 1);
  await page.screenshot({ path: 'artifacts/planner-entry-collapsed.png' });
  checks.push('Editor starts collapsed with Add below on the selected row; hidden controls are skipped by keyboard and accessibility navigation');
  await page.locator('.planner-row.is-current .planner-add-below').click();
  const quick = page.getByRole('textbox', { name: 'Quick entry', exact: true });
  assert(await quick.evaluate(el => el === document.activeElement));
  await quick.fill('13:00 mdr'); await quick.evaluate(el => el.setSelectionRange(2, 6));
  await page.getByRole('button', { name: 'Collapse activity editor', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.planner-capture').getBoundingClientRect().height <= 40);
  assert.equal(await toggle.textContent(), 'Continue your activity...');
  assert(await page.locator('.planner-capture-reveal').evaluate(el => el.inert));
  await toggle.press('Tab');
  assert(await page.evaluate(() => !document.activeElement.closest('.planner-capture-reveal')));
  await toggle.focus(); await toggle.press('Enter');
  assert.equal(await quick.inputValue(), '13:00 mdr');
  assert.deepEqual(await quick.evaluate(el => [el.selectionStart, el.selectionEnd, el === document.activeElement]), [2, 6, true]);
  checks.push('Closing preserves the draft and caret, uses Continue your activity, skips hidden controls with Tab, and reopens using Enter');
  await quick.press('Escape');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert(await toggle.evaluate(el => el === document.activeElement));
  await page.evaluate(() => app.workspace.getLeavesOfType('thejaz-planner')[0].view.refresh());
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await toggle.textContent(), 'Continue your activity...');
  assert.equal(await page.evaluate(() => app.plugins.plugins['thejaz-planner'].controller.port.read('2011-01-01.md')), initial);
  checks.push('Escape collapses and focuses the invitation; refresh preserves the closed draft without editing the note');
  await page.locator('.planner-row').nth(0).click();
  assert.equal(await page.locator('.planner-capture').evaluate(el => el.previousElementSibling.getAttribute('data-index')), '0');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  await page.locator('.planner-row').nth(1).focus();
  await page.locator('.planner-row').nth(1).getByRole('button', { name: 'Add below', exact: true }).click();
  assert(await quick.evaluate(el => el === document.activeElement));
  assert.equal(await quick.inputValue(), '13:00 mdr');
  checks.push('Closed invitation follows the insertion point; Add below reopens and focuses the existing draft');
  await page.locator('.planner-capture').evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(a => a.finished.catch(() => {}))); });
  await page.mouse.move(1, 1);
  await page.screenshot({ path: 'artifacts/planner-entry-expanded.png' });
  await quick.press('Enter');
  await page.waitForFunction(() => app.plugins.plugins['thejaz-planner'].controller.days.get('2011-01-01.md')?.text.includes('13:00 (60) : mdr') && getComputedStyle(document.querySelector('.planner-capture')).display === 'none');
  assert.equal(await toggle.textContent(), 'Add an activity...');
  assert(await page.locator('.planner-row.is-current .planner-add-below').evaluate(el => el === document.activeElement));
  assert.equal(await page.locator('.planner-capture').evaluate(el => el.previousElementSibling.getAttribute('data-index')), '2');
  checks.push('Successful submission clears the draft and focuses Add below without a redundant invitation');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('.planner-row.is-current .planner-add-below').click();
  assert.equal(await page.locator('.planner-capture-reveal').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await page.getByRole('button', { name: 'Collapse activity editor', exact: true }).click();
  await page.locator('.planner-shell').evaluate(el => { el.style.maxWidth = '320px'; });
  assert(await page.locator('.planner-capture').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.locator('.planner-row.is-current').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/planner-entry-collapsed-narrow.png' });
  checks.push('Collapse animation respects reduced motion and the invitation fits a 320px content area');
  assert.deepEqual(errors, []);
  await writeFile('artifacts/planner-collapse-entry.json', JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); }
